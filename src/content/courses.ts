export function parseCourses(source = COURSES_RAW): Course[] {
  return source
    .split(/\n(?=(?:MA|MCM|MGL)\d)/)
    .map((block) => block.trim())
    .filter(Boolean)
    .map((block) => {
      const lines = block.split("\n").map((l) => l.trim()).filter(Boolean);
      const code = lines[0] ?? "";
      const hasTitle = !!(lines[1] && !/^\d+\s*credits?/i.test(lines[1]) && !/^(MA|MCM|MGL)\d/.test(lines[1]));
      const creditIdx = hasTitle ? 2 : 1;
      const hasCredits = /^\d+\s*credits?/i.test(lines[creditIdx] ?? "");
      const bodyStart = hasTitle ? (hasCredits ? 3 : 2) : hasCredits ? 2 : 1;
      const body = lines
        .slice(bodyStart)
        .join("\n\n")
        .replace(/\n*Non-credit bearing Courses\s*$/i, "")
        .trim();
      return {
        code,
        title: hasTitle ? (lines[1] ?? "") : "",
        credits: hasCredits ? (lines[creditIdx] ?? "") : "",
        body,
      };
    })
    .filter((c) => /^(MA|MCM|MGL)\d/.test(c.code));
}
